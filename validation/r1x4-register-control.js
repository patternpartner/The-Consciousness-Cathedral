#!/usr/bin/env node
// R1.x run 4 — participant vs register: what drives the echo signature?
//
// After run 3, echo separates machine-machine from human dialogue at any
// turn length. But every machine-machine sample so far is in the assistant
// register. Two new populations complete the decomposition:
//
//   HH-task   MultiWOZ — human-human Wizard-of-Oz dialogues where a HUMAN
//             plays the assistant role. Assistant register, no machines.
//   AIAI-task CAMEL (ai_society) — two LLM agents collaborating on tasks.
//             A second machine-machine sample from a different generation
//             pipeline than UltraChat. Machines, different register.
//
// Pre-stated predictions (participant hypothesis):
//   P1: the human-assistant population stays at human echo levels — both
//       machine-machine populations exceed 3x HH-task under the
//       truncation control. If instead HH-task echoes like the machines,
//       the signature is register-driven and gets relabeled accordingly.
//   P2 (replication): CAMEL, generated by a different pipeline, shows the
//       machine echo signature (>3x every human population, truncated).

const fs = require('fs');
const path = require('path');
const { analyzeExchange } = require('../relational-core.js');

const DATA = path.join(__dirname, 'data');
const MIN_TURNS = 4;
const TRUNC = 30;
const BANDS = [[3, 15], [15, 40]];
const MIN_PAIRS = 30;

function loadDailyDialog() {
  const out = [];
  for (const off of [0, 100, 200]) {
    for (const { row } of JSON.parse(fs.readFileSync(path.join(DATA, `dd_${off}.json`))).rows) {
      const turns = row.utterances.map((u, i) => ({ speaker: i % 2 === 0 ? 'A' : 'B', text: u }));
      if (turns.length >= MIN_TURNS) out.push(turns);
    }
  }
  return out;
}
function loadHhRlhf() {
  const out = [];
  for (const off of [0, 100, 200]) {
    for (const { row } of JSON.parse(fs.readFileSync(path.join(DATA, `hh_${off}.json`))).rows) {
      const turns = [];
      const parts = row.chosen.split(/\n\n(Human|Assistant): /).slice(1);
      for (let i = 0; i + 1 < parts.length; i += 2) {
        const t = parts[i + 1].trim();
        if (t) turns.push({ speaker: parts[i], text: t });
      }
      if (turns.length >= MIN_TURNS) out.push(turns);
    }
  }
  return out;
}
function loadUltraChat() {
  const out = [];
  for (const off of [0, 100, 200]) {
    for (const { row } of JSON.parse(fs.readFileSync(path.join(DATA, `ua_${off}.json`))).rows) {
      const turns = row.messages
        .filter(m => m.role === 'user' || m.role === 'assistant')
        .map(m => ({ speaker: m.role === 'user' ? 'UserAI' : 'AssistantAI', text: m.content }));
      if (turns.length >= MIN_TURNS) out.push(turns);
    }
  }
  return out;
}
function loadMultiWoz() {
  const byDialogue = new Map();
  for (const f of fs.readdirSync(DATA).filter(f => f.startsWith('mw_'))) {
    for (const { row } of JSON.parse(fs.readFileSync(path.join(DATA, f))).rows) {
      let arr = byDialogue.get(row.dialogue_id);
      if (!arr) byDialogue.set(row.dialogue_id, arr = []);
      arr.push(row);
    }
  }
  const out = [];
  for (const rows of byDialogue.values()) {
    rows.sort((a, b) => a.turn_id - b.turn_id);
    const turns = [];
    for (const r of rows) {
      if (r.usr_utt && r.usr_utt.trim()) turns.push({ speaker: 'Customer', text: r.usr_utt.trim() });
      if (r.sys_utt && r.sys_utt.trim()) turns.push({ speaker: 'Operator', text: r.sys_utt.trim() });
    }
    if (turns.length >= MIN_TURNS) out.push(turns);
  }
  return out;
}
function loadCamel() {
  const byConv = new Map();
  for (const f of fs.readdirSync(DATA).filter(f => f.startsWith('cm_'))) {
    for (const { row } of JSON.parse(fs.readFileSync(path.join(DATA, f))).rows) {
      let arr = byConv.get(row.conversation_id);
      if (!arr) byConv.set(row.conversation_id, arr = []);
      arr.push(row);
    }
  }
  const out = [];
  for (const rows of byConv.values()) {
    rows.sort((a, b) => a.message_id - b.message_id);
    const turns = [];
    for (const r of rows) {
      const speaker = r.message_type === 'output' ? 'ExecutorAI' : 'InstructorAI';
      if (turns.length && turns[turns.length - 1].speaker === speaker) {
        turns[turns.length - 1].text += ' ' + r.message;
      } else {
        turns.push({ speaker, text: r.message });
      }
    }
    if (turns.length >= MIN_TURNS) out.push(turns);
  }
  return out;
}

const tokens = t => t.split(/\s+/).filter(Boolean).length;
const truncate = (dialogues, cap) => dialogues.map(dlg => dlg.map(t => ({
  speaker: t.speaker, text: t.text.split(/\s+/).filter(Boolean).slice(0, cap).join(' ')
})));

function stats(dialogues) {
  let opp = 0, echo = 0, uptake = 0;
  const bandCells = BANDS.map(() => ({ pairs: 0, echo: 0 }));
  for (const turns of dialogues) {
    const r = analyzeExchange(turns);
    opp += r.uptake.length;
    for (const e of r.uptake) {
      if (e.type === 'ECHO') echo++;
      if (e.type === 'TRANSFORMATIVE' || e.type === 'WEAK') uptake++;
      const lo = Math.min(tokens(turns[e.from].text), tokens(turns[e.to].text));
      const bi = BANDS.findIndex(([a, b]) => lo >= a && lo < b);
      if (bi >= 0) {
        bandCells[bi].pairs++;
        if (e.type === 'ECHO') bandCells[bi].echo++;
      }
    }
  }
  return {
    n: dialogues.length,
    pairs: opp,
    echoRate: +(echo / Math.max(1, opp)).toFixed(3),
    uptakeRate: +(uptake / Math.max(1, opp)).toFixed(3),
    bands: bandCells.map(c => ({ pairs: c.pairs, echoRate: c.pairs ? +(c.echo / c.pairs).toFixed(3) : null }))
  };
}

const pops = {
  'HH-casual (DailyDialog)': loadDailyDialog(),
  'HH-task (MultiWOZ)': loadMultiWoz(),
  'HAI (hh-rlhf)': loadHhRlhf(),
  'AIAI-assist (UltraChat)': loadUltraChat(),
  'AIAI-task (CAMEL)': loadCamel()
};

console.log('═'.repeat(78));
console.log('R1.x RUN 4 — participant vs register: the echo 2x2 completed');
console.log('═'.repeat(78));
console.log('\n  population              | n dlg | echo    uptake  | trunc-30 echo | band 3-15      band 15-40');

const out = {};
for (const [name, dialogues] of Object.entries(pops)) {
  const s = stats(dialogues);
  const st = stats(truncate(dialogues, TRUNC));
  out[name] = { full: s, truncated: { echoRate: st.echoRate, pairs: st.pairs } };
  const b = s.bands.map(x => x.echoRate === null ? '—' : `${(x.echoRate * 100).toFixed(1)}% [${x.pairs}]`);
  console.log(`  ${name.padEnd(23)} | ${String(s.n).padEnd(5)} | ${(s.echoRate * 100).toFixed(1).padEnd(6)}% ${(s.uptakeRate * 100).toFixed(1).padEnd(6)}% | ${(st.echoRate * 100).toFixed(1).padEnd(12)}% | ${b[0].padEnd(14)} ${b[1]}`);
}

const T = n => out[n].truncated.echoRate;
const floor = x => Math.max(0.005, x);
const p1 = T('AIAI-assist (UltraChat)') > 3 * floor(T('HH-task (MultiWOZ)')) &&
           T('AIAI-task (CAMEL)') > 3 * floor(T('HH-task (MultiWOZ)'));
const humans = ['HH-casual (DailyDialog)', 'HH-task (MultiWOZ)', 'HAI (hh-rlhf)'];
const p2 = humans.every(h => T('AIAI-task (CAMEL)') > 3 * floor(T(h)));

console.log('\n' + '═'.repeat(78));
console.log(`P1 (human-assistant register stays human-level): ${p1 ? 'HELD' : 'FAILED'}`);
console.log(`P2 (CAMEL replicates the machine signature):      ${p2 ? 'HELD' : 'FAILED'}`);
console.log(p1 && p2
  ? 'The echo signature tracks PARTICIPANTS, not register, and replicates\nacross machine-generation pipelines.'
  : 'At least one prediction failed — the signature is not (only) participant-\ndriven. Relabel per program rules.');
console.log('═'.repeat(78));

fs.writeFileSync(path.join(__dirname, 'results-run4.json'),
  JSON.stringify({ date: new Date().toISOString(), populations: out, predictions: { p1, p2 } }, null, 2));
console.log('\nresults written to validation/results-run4.json');
